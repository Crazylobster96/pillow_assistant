"""Vendor the text-to-cad Skills into Pillow and record which upstream release they came from.

Upstream: https://github.com/earthtojake/text-to-cad.  Its ``latest`` branch holds
only the plugin (skills + MCP configs) and receives each release once that release's
``cadgen`` runtime is on PyPI, so following it never pins a cadgen that cannot be
installed yet.

    python scripts/sync_text_to_cad.py               # sync from upstream `latest`
    python scripts/sync_text_to_cad.py --ref v0.7.26 # a specific tag/branch
    python scripts/sync_text_to_cad.py --source DIR  # from an existing checkout
    python scripts/sync_text_to_cad.py --check       # exit 1 if an update is available

The vendored tree lives in ``pillow_assistant/capabilities/skills/text_to_cad/``
and is replaced wholesale on every sync; never edit it by hand.  Pillow-specific
adaptation lives in Python (the ``text_to_cad`` / ``cad_reference`` tools and the
Skill preamble), so upstream files stay byte-identical and diffs stay readable.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = "earthtojake/text-to-cad"
DEFAULT_REF = "latest"
ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "pillow_assistant" / "capabilities" / "skills" / "text_to_cad"
SKIP_DIRS = {"agents", "__pycache__"}  # per-agent UI metadata (e.g. openai.yaml) is not used by Pillow


def _git(*args: str, cwd: Path | None = None) -> str:
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


def fetch(ref: str, into: Path) -> Path:
    url = f"https://github.com/{REPO}.git"
    _git("clone", "--quiet", "--depth", "1", "--branch", ref, url, str(into))
    return into


def read_upstream(src: Path) -> dict:
    """Release metadata from an upstream checkout: plugin version and the uvx invocation of cadgen."""
    plugin = json.loads((src / "plugin.json").read_text("utf-8"))
    server = json.loads((src / "mcp.json").read_text("utf-8"))["mcpServers"]["cad"]
    args = list(server["args"])
    # [..., "--from", "cadgen==X", "cadgen", "mcp"]: keep everything before the entry point.
    entry = args.index("--from") + 2
    pin = args[entry - 1]
    if not pin.startswith("cadgen=="):
        raise SystemExit(f"unexpected cadgen pin in mcp.json: {pin!r}")
    try:
        commit = _git("rev-parse", "HEAD", cwd=src)
    except (subprocess.CalledProcessError, OSError):
        commit = ""
    return {
        "repo": REPO,
        "version": plugin["version"],
        "cadgen_version": pin.split("==", 1)[1],
        "commit": commit,
        "uvx_args": args[:entry],
    }


def vendor(src: Path, dest: Path, meta: dict, ref: str) -> None:
    skills = src / "skills"
    if not skills.is_dir():
        raise SystemExit(f"no skills/ in {src}")
    staging = dest.with_name(dest.name + ".new")
    if staging.exists():
        shutil.rmtree(staging)
    shutil.copytree(skills, staging, ignore=shutil.ignore_patterns(*SKIP_DIRS, "*.pyc"))
    if (src / "LICENSE").is_file():
        shutil.copy2(src / "LICENSE", staging / "LICENSE")
    info = {"_comment": "Generated by scripts/sync_text_to_cad.py; do not edit.", "ref": ref, **meta}
    (staging / "UPSTREAM.json").write_text(json.dumps(info, indent=2, ensure_ascii=False) + "\n", "utf-8")
    if dest.exists():
        shutil.rmtree(dest)
    staging.rename(dest)


def current() -> dict:
    try:
        return json.loads((DEST / "UPSTREAM.json").read_text("utf-8"))
    except (OSError, ValueError):
        return {}


def _output(**values: str) -> None:
    target = os.environ.get("GITHUB_OUTPUT")
    if target:
        with open(target, "a", encoding="utf-8") as fh:
            for key, value in values.items():
                fh.write(f"{key}={value}\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ref", default=DEFAULT_REF, help="upstream branch or tag (default: latest)")
    parser.add_argument("--source", type=Path, help="use an existing upstream checkout instead of cloning")
    parser.add_argument("--check", action="store_true", help="only report; exit 1 when an update is available")
    opts = parser.parse_args(argv)

    before = current()
    with tempfile.TemporaryDirectory() as tmp:
        src = opts.source.resolve() if opts.source else fetch(opts.ref, Path(tmp) / "text-to-cad")
        meta = read_upstream(src)
        changed = (before.get("commit"), before.get("version")) != (meta["commit"], meta["version"])
        if opts.source and not meta["commit"]:
            changed = True
        print(f"text-to-cad: vendored {before.get('version') or '-'}, upstream {meta['version']} "
              f"(cadgen {meta['cadgen_version']}, {meta['commit'][:12] or 'local'})")
        _output(changed=str(changed).lower(), version=meta["version"], previous=before.get("version") or "")
        if opts.check:
            return 1 if changed else 0
        vendor(src, DEST, meta, opts.ref)
    print(f"synced into {DEST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
