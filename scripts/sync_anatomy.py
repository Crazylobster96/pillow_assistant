"""Vendor the Anatomy Skill into Pillow and record which upstream release it came from.

Upstream: https://github.com/wheresryan22/anatomy.  It tags releases ``vX.Y.Z``;
by default the newest tag is synced, so unreleased work on its main branch never
reaches users.

    python scripts/sync_anatomy.py               # sync the newest release tag
    python scripts/sync_anatomy.py --ref v1.1.0  # a specific tag/branch
    python scripts/sync_anatomy.py --source DIR  # from an existing checkout
    python scripts/sync_anatomy.py --check       # exit 1 if an update is available

The vendored tree lives in ``pillow_assistant/capabilities/skills/anatomy/anatomy/``
and is replaced wholesale on every sync; never edit it by hand.  Files are copied
byte for byte, except what Pillow never uses: repository chrome (.github, tests,
contributor docs), per-agent metadata, the kit's own unit tests, and the built
pages and PDFs under examples/ (a figure's build.mjs regenerates them, and they
are most of the repository's size).  Pillow-specific adaptation lives in Python
(the ``anatomy`` / ``anatomy_reference`` tools and the Skill preamble).
"""

from __future__ import annotations

import argparse
import fnmatch
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = "wheresryan22/anatomy"
DEFAULT_REF = "release"  # the newest vX.Y.Z tag
ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "pillow_assistant" / "capabilities" / "skills" / "anatomy"
SKILL = "anatomy"
SKIP_TOP = {".git", ".github", "tests", "agents", "evals", "CODE_OF_CONDUCT.md", "CONTRIBUTING.md",
            "SECURITY.md", ".gitattributes", ".gitignore"}
SKIP_GLOBS = ("examples/*.html", "examples/*.pdf", "examples/*.png", "examples/*.webp",
              "scripts/*.test.mjs", "*/__pycache__/*", "*/node_modules/*", "*/shots/*")
NODE_MIN = "20.10"


def _git(*args: str, cwd: Path | None = None) -> str:
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


def _version_key(tag: str) -> tuple:
    return tuple(int(n) for n in re.findall(r"\d+", tag))


def newest_tag() -> str:
    out = _git("ls-remote", "--tags", "--refs", f"https://github.com/{REPO}.git")
    tags = [line.rsplit("refs/tags/", 1)[1] for line in out.splitlines() if "refs/tags/" in line]
    tags = [t for t in tags if re.fullmatch(r"v?\d+\.\d+\.\d+", t)]
    if not tags:
        raise SystemExit(f"no release tags on {REPO}")
    return max(tags, key=_version_key)


def fetch(ref: str, into: Path) -> Path:
    _git("clone", "--quiet", "--depth", "1", "--branch", ref, f"https://github.com/{REPO}.git", str(into))
    return into


def skipped(rel: str) -> bool:
    if rel.split("/", 1)[0] in SKIP_TOP:
        return True
    # examples/<name>/<file>: built outputs are regenerated by the example's build.mjs.
    flat = re.sub(r"^examples/[^/]+/", "examples/", rel)
    return any(fnmatch.fnmatch(rel, g) or fnmatch.fnmatch(flat, g) for g in SKIP_GLOBS)


def read_upstream(src: Path, ref: str) -> dict:
    if not (src / "SKILL.md").is_file():
        raise SystemExit(f"no SKILL.md in {src}")
    try:
        commit = _git("rev-parse", "HEAD", cwd=src)
    except (subprocess.CalledProcessError, OSError):
        commit = ""
    version = ref.lstrip("v") if re.fullmatch(r"v?\d+\.\d+\.\d+", ref) else ref
    return {"repo": REPO, "version": version, "commit": commit, "node_min": NODE_MIN}


def vendor(src: Path, dest: Path, meta: dict, ref: str) -> int:
    staging = dest.with_name(dest.name + ".new")
    if staging.exists():
        shutil.rmtree(staging)
    target = staging / SKILL
    count = 0
    for path in sorted(src.rglob("*")):
        rel = path.relative_to(src).as_posix()
        if not path.is_file() or skipped(rel):
            continue
        out = target / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, out)
        count += 1
    info = {"_comment": "Generated by scripts/sync_anatomy.py; do not edit.", "ref": ref, **meta}
    (staging / "UPSTREAM.json").write_text(json.dumps(info, indent=2, ensure_ascii=False) + "\n", "utf-8")
    if dest.exists():
        shutil.rmtree(dest)
    staging.rename(dest)
    return count


def current() -> dict:
    try:
        return json.loads((DEST / "UPSTREAM.json").read_text("utf-8"))
    except (OSError, ValueError):
        return {}


def _output(**values: str) -> None:
    target = os.environ.get("GITHUB_OUTPUT")
    if target:
        with open(target, "a", encoding="utf-8") as fh:
            for key, value in values.items():
                fh.write(f"{key}={value}\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ref", default=DEFAULT_REF,
                        help="upstream tag or branch (default: the newest release tag)")
    parser.add_argument("--source", type=Path, help="use an existing upstream checkout instead of cloning")
    parser.add_argument("--check", action="store_true", help="only report; exit 1 when an update is available")
    opts = parser.parse_args(argv)

    before = current()
    ref = newest_tag() if opts.ref in ("", DEFAULT_REF) and not opts.source else opts.ref
    with tempfile.TemporaryDirectory() as tmp:
        src = opts.source.resolve() if opts.source else fetch(ref, Path(tmp) / "anatomy")
        meta = read_upstream(src, ref)
        changed = (before.get("commit"), before.get("version")) != (meta["commit"], meta["version"])
        if opts.source and not meta["commit"]:
            changed = True
        print(f"anatomy: vendored {before.get('version') or '-'}, upstream {meta['version']} "
              f"({meta['commit'][:12] or 'local'})")
        _output(changed=str(changed).lower(), version=meta["version"], previous=before.get("version") or "")
        if opts.check:
            return 1 if changed else 0
        count = vendor(src, DEST, meta, ref)
    print(f"synced {count} files into {DEST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
